class Store:
    def __init__(self):
        self.lock = threading.Lock()
        self.seq = 0
        self.logs = {}  # ns -> [record]
        self.attempts = {}  # (ns, scenario, body sha256) -> [monotonic time of each attempt]
        self.in_flight = {}  # ns -> API requests being answered

    def reset(self, ns):
        with self.lock:
            self.logs.pop(ns, None)
            for key in [k for k in self.attempts if k[0] == ns]:
                del self.attempts[key]

    def attempt(self, ns, scenario, digest):
        """(1-based attempt number of this body, ms since its previous attempt or None)."""
        now = time.monotonic()
        with self.lock:
            times = self.attempts.setdefault((ns, scenario, digest), [])
            waited = round((now - times[-1]) * 1000, 1) if times else None
            times.append(now)
            return len(times), waited

    def enter(self, ns):
        """The namespace's API requests in flight, this one included."""
        with self.lock:
            self.in_flight[ns] = self.in_flight.get(ns, 0) + 1
            return self.in_flight[ns]

    def leave(self, ns):
        with self.lock:
            self.in_flight[ns] -= 1

    def append(self, ns, record):
        with self.lock:
            self.seq += 1
            record["seq"] = self.seq
            self.logs.setdefault(ns, []).append(record)
            return self.seq

    def ndjson(self, ns):
        with self.lock:
            records = list(self.logs.get(ns, []))
        marker = _record(ns=ns, endpoint="(log)", method="GET", seq=0)
        return "".join(json.dumps(r, separators=(",", ":")) + "\n" for r in [marker, *records]).encode()


