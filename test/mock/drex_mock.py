#!/usr/bin/env python3
"""A small, deterministic mock of Drex's POST /v1/systemone and GET /v1/models, for the SQLLogicTests.

Standard library only. Shapes follow Drex's openapi.json (SystemOneRequest, SystemOneResponse, ModelsResponse,
ErrorEnvelope) and the validation in its lib/ndm.ts, so a request the real API would refuse is refused here too.

Routes:

- `/ns/<ns>/<scenario>/v1/systemone` and `/ns/<ns>/<scenario>/v1/models`: the API. Point a secret's BASE_URL at
  `<mock>/ns/<ns>/<scenario>`. `<ns>` keeps one test file's requests apart from another's; `<scenario>` picks the
  behaviour (see SCENARIOS). `/v1/...` without a prefix is namespace `default`, scenario `ok`.
- `GET /__log/<ns>`: the namespace's requests as newline-delimited JSON, one record per request (see `_record`).
  The first line is always a marker record with `endpoint` `(log)`, so the body is never empty.
- `GET /__reset/<ns>`: forgets the namespace's requests and retry counters.
- `GET /__fixtures/red.png`, `/__fixtures/blue.png`: solid-colour PNGs generated by pngs.py.
- `GET /__fixtures/openrouter.pem`: the self-signed certificate the mock serves for openrouter.ai, for DuckDB's
  `ca_cert_file`. Made with the `openssl` command on first use.
- `GET /__health`: `ok`.
- OpenRouter: through the mock as DuckDB's `http_proxy`, a request for `https://openrouter.ai/api/<route>` (tunnelled
  with CONNECT, and answered with that certificate) or `http://openrouter.ai/api/<route>` is answered as OpenRouter
  answers it, on the same routes (see `from_open_router`). Every other proxied request is served as usual.

GET routes answer HEAD and byte ranges and are never cacheable, so DuckDB's httpfs can read them with read_json,
read_text and read_blob.

Run: python3 test/mock/drex_mock.py [--host 127.0.0.1] [--port 8787] [--url-file path]
"""

