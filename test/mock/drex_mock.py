API_PATH = re.compile(r"^(?:/ns/(?P<ns>[A-Za-z0-9_.-]+)/(?P<scenario>[A-Za-z0-9_.-]+))?(?P<endpoint>/v1/[a-z]+)$")


class Handler(OpenRouterTunnel, BaseHTTPRequestHandler):
    protocol_version = "HTTP/1.1"
    server_version = "drex-mock/1"
    store: Store = None  # set by make_server
    quiet = True
    in_flight_ns = None  # the namespace of the API request being answered on this connection

    def log_message(self, format, *args):  # noqa: A002 - BaseHTTPRequestHandler's signature
        if not self.quiet:
            super().log_message(format, *args)

    # -- responses ------------------------------------------------------------------------------------------------

    def _send(self, status, body, content_type, headers=None, head=False):
        self.send_response(status)
        self.send_header("Content-Type", content_type)
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Cache-Control", "no-store")
        for name, value in (headers or {}).items():
            self.send_header(name, value)
        self._leave()
        self.end_headers()
        if not head:
            self.wfile.write(body)

    def _send_resource(self, body, content_type, head):
        """A GET resource, with HEAD and single byte ranges, as httpfs reads files."""
        headers = {"Accept-Ranges": "bytes"}
        match = re.match(r"^bytes=(\d+)-(\d*)$", self.headers.get("Range", ""))
        if match and body:
            start = int(match.group(1))
            end = min(int(match.group(2)) if match.group(2) else len(body) - 1, len(body) - 1)
            if start > end:
                self._send(416, b"", content_type, {"Content-Range": f"bytes */{len(body)}"}, head)
                return
            headers["Content-Range"] = f"bytes {start}-{end}/{len(body)}"
            self._send(206, body[start : end + 1], content_type, headers, head)
            return
        self._send(200, body, content_type, headers, head)

    def _send_api(self, status, payload, request_id, retry_after_ms=None):
        headers = {
            "x-request-id": request_id,
            "x-typesafe-request-id": request_id,
            "access-control-expose-headers": "retry-after, retry-after-ms, x-request-id, x-typesafe-request-id, "
            "www-authenticate",
        }
        if retry_after_ms is not None:
            headers["retry-after-ms"] = str(retry_after_ms)
            headers["retry-after"] = str(math.ceil(retry_after_ms / 1000))
        body = json.dumps(payload, separators=(",", ":")).encode()
        self._send(status, body, "application/json", headers)

    @staticmethod
    def _error(error, request_id, issues=None):
        status, kind, message = error
        body = {"type": kind, "message": message}
        if issues is not None:
            body["issues"] = issues
        return status, {"error": body, "request_id": request_id}

    def _leave(self):
        """Stops counting this connection's API request as in flight, before the client can read its answer."""
        if self.in_flight_ns is not None:
            self.store.leave(self.in_flight_ns)
            self.in_flight_ns = None

    # -- routing --------------------------------------------------------------------------------------------------

    def do_HEAD(self):  # noqa: N802 - BaseHTTPRequestHandler's naming
        self._get(head=True)

    def do_GET(self):  # noqa: N802
        self._get(head=False)

    def do_POST(self):  # noqa: N802
        length = int(self.headers.get("Content-Length") or 0)
        body = self.rfile.read(length) if length else b""
        self._api("POST", body)

    def _target(self):
        """(path, query, whether it is for OpenRouter). A request through a proxy names its URL in full, and one
        through a tunnel only its path."""
        url = urllib.parse.urlsplit(self.path)
        open_router = (self.tunnel_host or url.hostname) == OPEN_ROUTER_HOST and url.path.startswith("/api/")
        return (url.path[len("/api") :] if open_router else url.path), url.query, open_router

    def _get(self, head):
        path = self._target()[0]
        if path == "/__health":
            self._send_resource(b"ok\n", "text/plain", head)
        elif path.startswith("/__log/"):
            self._send_resource(self.store.ndjson(path[len("/__log/") :]), "application/x-ndjson", head)
        elif path.startswith("/__reset/"):
            self.store.reset(path[len("/__reset/") :])
            self._send_resource(b"ok\n", "text/plain", head)
        elif path.startswith("/__fixtures/") and path.endswith(".png") and path[12:-4] in pngs.COLOURS:
            self._send_resource(pngs.fixture(path[12:-4]), "image/png", head)
        elif path == "/__fixtures/openrouter.pem":
            self._send_resource(OpenRouterTls.certificate(), "application/x-pem-file", head)
        elif head:
            self._send(404, b"", "text/plain", head=True)
        else:
            self._api("GET", b"")

    def _api(self, method, body_bytes):
        path, query, open_router = self._target()
        match = API_PATH.match(path)
        endpoint = match and match.group("endpoint")
        if endpoint not in ("/v1/systemone", "/v1/models") or (method == "POST") != (endpoint == "/v1/systemone"):
            self._send(404, b'{"error":"not found"}', "application/json")
            return
        ns = match.group("ns") or "default"
        scenario = match.group("scenario") or "ok"
        in_flight = self.store.enter(ns)
        self.in_flight_ns = ns
        try:
            self._answer(ns, scenario, endpoint, method, body_bytes, query, open_router, in_flight)
        finally:
            self._leave()

    def _answer(self, ns, scenario, endpoint, method, body_bytes, query, open_router, in_flight):
        record = _record(
            in_flight=in_flight,
            received_at=time.time(),
            open_router=open_router,
            ns=ns,
            scenario=scenario,
            method=method,
            endpoint=endpoint,
            authorization_header=self.headers.get("Authorization"),
            user_agent=self.headers.get("User-Agent"),
            x_nace_client=self.headers.get("X-Nace-Client"),
            idempotency_key=self.headers.get("Idempotency-Key"),
            content_type=self.headers.get("Content-Type"),
            http_referer=self.headers.get("HTTP-Referer"),
            x_openrouter_title=self.headers.get("X-OpenRouter-Title"),
        )
        seq = self.store.append(ns, record)
        request_id = "req_" + hashlib.md5(f"{ns}/{seq}".encode()).hexdigest()
        if not known_scenario(scenario):
            status, payload = 404, {"error": f"unknown scenario {scenario!r}; one of {sorted(SCENARIOS)}"}
            record["status"] = status
            self._send(status, json.dumps(payload).encode(), "application/json")
            return
        if endpoint == "/v1/models":
            status, payload = self._models(scenario, request_id, open_router, query)
            retry_after_ms = None
        else:
            status, payload, retry_after_ms = self._systemone(scenario, body_bytes, record, request_id, open_router)
        record["status"] = status
        record["retry_after_ms"] = retry_after_ms
        self._send_api(status, payload, request_id, retry_after_ms)

    # -- endpoints ------------------------------------------------------------------------------------------------

    def _authorized(self, scenario, open_router=False):
        pattern = OPEN_ROUTER_KEY_PATTERN if open_router else KEY_PATTERN
        return scenario != "401" and pattern.match(self.headers.get("Authorization") or "")

    def _models(self, scenario, request_id, open_router=False, query=""):
        if not self._authorized(scenario, open_router):
            return self._error(INVALID_KEY, request_id)
        if open_router:
            return 200, self._open_router_models(query)
        models = [
            {"name": name, "description": m["description"], "release_date": m["release_date"], "alias_for": None}
            for name, m in SERVED.items()
        ]
        for alias, target in ALIASES.items():
            models.append(
                {
                    "name": alias,
                    "description": f"Points to {target} ({SERVED[target]['label']}). Moves to a newer version only on "
                    "an announced date.",
                    "release_date": SERVED[target]["release_date"],
                    "alias_for": target,
                }
            )
        for name, retired in RETIRED.items():
            served = retired["served_by"]
            models.append(
                {
                    "name": name,
                    "description": f"Retired on {retired['on']}. Requests that name it are served by {served} "
                    f"({SERVED[served]['label']}) at its price.",
                    "release_date": retired["release_date"],
                    "alias_for": served,
                }
            )
        return 200, {"models": models, "request_id": request_id}

    @staticmethod
    def _open_router_models(query):
        """OpenRouter's list, of text models unless output_modalities=decisions asks for decision models."""

        def listed(model_id, inputs, output):
            return {"id": model_id, "architecture": {"input_modalities": inputs, "output_modalities": [output]}}

        if "decisions" not in urllib.parse.parse_qs(query).get("output_modalities", []):
            return {"data": [listed("openai/gpt-5", ["text", "image"], "text")]}
        nace = [
            listed(f"nace-ai/{name}", ["text", "image"] if name in IMAGE_MODELS else ["text"], "decisions")
            for name in OPEN_ROUTER_MODELS
        ]
        return {"data": [listed("liquid/d1.1", ["text", "image"], "decisions"), *nace]}

    def _systemone(self, scenario, body_bytes, record, request_id, open_router=False):
        digest = hashlib.sha256(body_bytes).hexdigest()
        attempt, waited = self.store.attempt(record["ns"], scenario, digest)
        record.update(body=body_bytes.decode("utf-8", "replace"), body_sha256=digest, attempt=attempt, waited_ms=waited)
        try:
            body = json.loads(body_bytes)
        except ValueError:
            body = None
        if isinstance(body, dict):
            self._describe(body, record)

        slow = SLOW.match(scenario)
        if slow:
            time.sleep(int(slow.group("ms")) / 1000)
        # The order of Drex's checks: key and credit, rate limits, then the body
        if not self._authorized(scenario, open_router):
            return (*self._error(INVALID_KEY, request_id), None)
        if scenario == "402":
            return (*self._error(NO_CREDIT, request_id), None)
        if scenario == "529-always" or (scenario in ("429-once", "529-once") and attempt == 1):
            error = RPM if scenario == "429-once" else CAPACITY
            return (*self._error(error, request_id), RETRY_AFTER_MS[scenario])
        if scenario == "422":
            status, payload = self._error(
                (422, "invalid_request_error", "questions.a.instructions: must be a string"), request_id, TWO_ISSUES
            )
            return status, payload, None
        if body is None:
            issues = [_issue("", "request body must be valid JSON")]
            return (*self._error((422, "invalid_request_error", issues[0]["message"]), request_id, issues), None)
        if open_router:
            body, refusal = from_open_router(body)
            if refusal:
                return 400, {"error": {"message": refusal, "code": 400}}, None

        model, issues = validate(body_bytes, body)
        if issues:
            first = issues[0]
            message = f"{first['path']}: {first['message']}" if first["path"] else first["message"]
            return (*self._error((422, "invalid_request_error", message), request_id, issues), None)
        refusal = too_long(body, model) if scenario == "too-long" else None
        if refusal:
            message, issues = refusal
            return (*self._error((422, "invalid_request_error", message), request_id, issues), None)
        record["served_model"] = model
        images = [decode_image(i) for i in body.get("images") or []]
        answers = {qid: answer(q, images) for qid, q in body["questions"].items()}
        usage = {"input_tokens": max(1, len(body_bytes) // 4), "output_tokens": 2 * len(answers)}
        if images:
            usage["image_tokens"] = IMAGE_TOKENS * len(images)
            usage["input_tokens"] += usage["image_tokens"]
        return (
            200,
            {
                "model": f"nace-ai/{model}" if open_router else model,
                "answers": answers,
                "usage": usage,
                "evaluation_time_ms": 12.5,
                "request_id": request_id,
            },
            None,
        )

    @staticmethod
    def _describe(body, record):
        """The log fields that the SQL tests assert on, taken from a parsed body."""
        questions = body.get("questions")
        listed = (
            [{"id": qid, **q} if isinstance(q, dict) else {"id": qid, "invalid": q} for qid, q in questions.items()]
            if isinstance(questions, dict)
            else []
        )
        images = body.get("images") if isinstance(body.get("images"), list) else _state_images(body.get("state"))
        record.update(
            model=body.get("model") if isinstance(body.get("model"), str) else None,
            model_present="model" in body,
            state_type=_json_type(body["state"]) if "state" in body else None,
            state=json.dumps(body["state"], separators=(",", ":")) if "state" in body else None,
            question_count=len(listed),
            # Every question carries `instructions` as a string (Drex refuses null)
            instructions_present=bool(listed) and all(isinstance(q.get("instructions"), str) for q in listed),
            questions=json.dumps(listed, separators=(",", ":")),
            image_count=len(images),
            image_colours=[pngs.colour_of(decode_image(i) or b"") for i in images],
        )


class Server(ThreadingHTTPServer):
    # Room for every connection a concurrency test opens at once; past the backlog, macOS drops the connect
    request_queue_size = 256


def make_server(host="127.0.0.1", port=0, quiet=True):
    handler = type("BoundHandler", (Handler,), {"store": Store(), "quiet": quiet})
    server = Server((host, port), handler)
    server.daemon_threads = True
    return server


