class OpenRouterTls:
    """A self-signed certificate for openrouter.ai, made once, and the server context that presents it."""

    _lock = threading.Lock()
    _directory = None

    @classmethod
    def _files(cls):
        with cls._lock:
            if cls._directory is None:
                directory = tempfile.TemporaryDirectory(prefix="drex-mock-tls-")
                subprocess.run(
                    ["openssl", "req", "-x509", "-newkey", "rsa:2048", "-nodes", "-days", "7",
                     "-subj", f"/CN={OPEN_ROUTER_HOST}", "-addext", f"subjectAltName=DNS:{OPEN_ROUTER_HOST}",
                     "-keyout", f"{directory.name}/key.pem", "-out", f"{directory.name}/cert.pem"],
                    check=True, capture_output=True,
                )  # fmt: skip
                cls._directory = directory
            return f"{cls._directory.name}/cert.pem", f"{cls._directory.name}/key.pem"

    @classmethod
    def certificate(cls):
        return Path(cls._files()[0]).read_bytes()

    @classmethod
    def context(cls):
        context = ssl.SSLContext(ssl.PROTOCOL_TLS_SERVER)
        context.load_cert_chain(*cls._files())
        return context


class OpenRouterTunnel:
    """A BaseHTTPRequestHandler mixin that answers CONNECT openrouter.ai:443 by terminating TLS itself, with
    OpenRouterTls's certificate, and then handling the tunnel's requests as its own."""

    tunnel_host = None  # the host a CONNECT asked for, once this connection is a TLS tunnel to it

    def do_CONNECT(self):  # noqa: N802 - BaseHTTPRequestHandler's naming
        if self.tunnel_host is not None or self.path != f"{OPEN_ROUTER_HOST}:443":
            self.send_error(502, "the mock tunnels only to openrouter.ai:443")
            return
        self.send_response(200, "Connection established")
        self.end_headers()
        self.wfile.flush()
        self.connection = OpenRouterTls.context().wrap_socket(self.connection, server_side=True)
        self.rfile = self.connection.makefile("rb", self.rbufsize)
        self.wfile = self.connection.makefile("wb")
        self.tunnel_host = OPEN_ROUTER_HOST
        self.close_connection = False

    def finish(self):
        super().finish()
        if self.tunnel_host is not None:
            self.connection.close()


