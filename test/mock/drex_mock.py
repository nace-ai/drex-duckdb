def _normalised(weights):
    total = sum(weights)
    probabilities = [round(w / total, 4) for w in weights]
    probabilities[0] = round(probabilities[0] + 1 - sum(probabilities), 4)
    return probabilities


def _image_number(instructions):
    match = re.search(r"\bImage (\d+)\b", instructions or "")
    return int(match.group(1)) if match else 1


def answer(question, images):
    """The answer to one valid question.

    - A documented example question gets its documented answer.
    - A choice with `red` and `blue` labels, on a request with images, picks the colour of the image its instructions
      name (`Image N`, default Image 1).
    - Otherwise: a noul is 0.75 (confidence 0.75); a choice picks its first label, with weights n, n-1, ..., 1; a score weights its
      levels 1, 2, ..., n.
    """
    for documented, documented_answer in DOCUMENTED:
        if all(question.get(k) == documented.get(k) for k in ("type", "instructions", "criteria")):
            return documented_answer
    qtype, criteria = question["type"], question.get("criteria")
    if qtype == "noul":
        return {"type": "noul", "noul": 0.75, "confidence": 0.75}
    if qtype == "choice":
        labels = list(criteria)
        number = _image_number(question.get("instructions"))
        if images and {"red", "blue"} <= set(labels) and 1 <= number <= len(images):
            colour = pngs.colour_of(images[number - 1])
            if colour in labels:
                rest = round(0.03 / (len(labels) - 1), 4)
                probabilities = {label: (0.97 if label == colour else rest) for label in labels}
                return {"type": "choice", "choice": colour, "confidence": 0.96, "probabilities": probabilities}
        probabilities = _normalised([len(labels) - i for i in range(len(labels))])
        return {
            "type": "choice",
            "choice": labels[0],
            "confidence": 0.9,
            "probabilities": dict(zip(labels, probabilities)),
        }
    probabilities = _normalised([i + 1 for i in range(len(criteria))])
    return {
        "type": "score",
        "score": round(sum(i * p for i, p in enumerate(probabilities)), 4),
        "legend": list(criteria),
        "probabilities": {str(i): p for i, p in enumerate(probabilities)},
        "confidence": 0.8,
    }


