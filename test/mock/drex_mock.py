def _issue(path, message):
    return {"path": path, "message": message}


def _parse_question(qid, raw, issues):
    path = f"questions.{qid}"
    if not isinstance(raw, dict):
        issues.append(_issue(path, "must be an object"))
        return
    qtype = raw.get("type")
    if qtype not in ("noul", "choice", "score"):
        issues.append(_issue(f"{path}.type", 'must be "noul", "choice", or "score"'))
        return
    if "instructions" in raw and not isinstance(raw["instructions"], str):
        issues.append(_issue(f"{path}.instructions", "must be a string"))
    criteria = raw.get("criteria")
    if qtype == "noul":
        has_criterion = False
        if criteria is not None:
            if not isinstance(criteria, dict):
                issues.append(_issue(f"{path}.criteria", "must be an object"))
                return
            for key in ("true", "false"):
                value = criteria.get(key)
                if value is None:
                    continue
                if not isinstance(value, str):
                    issues.append(_issue(f"{path}.criteria.{key}", "must be a string"))
                elif value != "":
                    has_criterion = True
        has_instructions = isinstance(raw.get("instructions"), str) and raw["instructions"] != ""
        if not has_instructions and not has_criterion:
            issues.append(_issue(f"{path}.instructions", "noul needs instructions or criteria"))
        return
    if qtype == "choice":
        if not isinstance(criteria, dict):
            issues.append(_issue(f"{path}.criteria", "must be an object with options"))
            return
        if not criteria:
            issues.append(_issue(f"{path}.criteria", "choice needs at least 1 option"))
        for key, value in criteria.items():
            if value is not None and not isinstance(value, str):
                issues.append(_issue(f"{path}.criteria.{key}", "must be a string or null"))
        return
    if not isinstance(criteria, list):
        issues.append(_issue(f"{path}.criteria", "must be an array of level labels"))
        return
    if not criteria:
        issues.append(_issue(f"{path}.criteria", "score needs at least 1 level"))
    for i, level in enumerate(criteria):
        if not isinstance(level, str):
            issues.append(_issue(f"{path}.criteria.{i}", "must be a string"))


def resolve_model(name):
    """(served model id, None) or (None, issue message)."""
    if name is None:
        return ALIASES["drex-latest"], None
    if not isinstance(name, str):
        return None, "must be a string"
    if name in SERVED:
        return name, None
    if name in ALIASES:
        return ALIASES[name], None
    if name in RETIRED:
        return RETIRED[name]["served_by"], None
    if MODEL_PATTERN.match(name):
        # Drex serves any other drex-* or nacedm-* name as drex-latest (lib/models.ts); the extension must not rely
        # on this, which is why it checks /v1/models at bind time
        return ALIASES["drex-latest"], None
    names = ", ".join(f'"{m}"' for m in SERVED)
    return None, f'unknown model "{name}"; use {names} or "drex-latest"'


def decode_image(value):
    """The bytes of a base64 string or data URL, or None when it is neither."""
    if not isinstance(value, str):
        return None
    if value.startswith("data:"):
        match = DATA_URL_PATTERN.match(value)
        encoded = match.group(1) if match else None
    else:
        encoded = value
    if not encoded or len(encoded) % 4 or not BASE64_PATTERN.match(encoded):
        return None
    try:
        return base64.b64decode(encoded, validate=True)
    except ValueError:
        return None


def from_open_router(body):
    """(the Drex body an OpenRouter body stands for, None) or (None, why OpenRouter answers 400).

    OpenRouter takes a model under nace-ai/, refuses a question without instructions and top-level images, and takes
    images as data URLs in `state` content parts after the state as text (Drex's docs/openrouter-mirroring.md).
    """
    if not isinstance(body, dict):
        return None, "must be a JSON object"
    model = body.get("model")
    if not isinstance(model, str) or model.removeprefix("nace-ai/") not in OPEN_ROUTER_MODELS or "/" not in model:
        return None, f"{model} is not a valid model ID"
    if "images" in body:
        return None, "images must be sent as state content parts"
    questions = body.get("questions")
    if isinstance(questions, dict) and any(
        not isinstance(q, dict) or not isinstance(q.get("instructions"), str) for q in questions.values()
    ):
        return None, "every question needs instructions"
    drex = {**body, "model": model.removeprefix("nace-ai/")}
    state = body.get("state")
    if isinstance(state, list):
        text = [p.get("text") for p in state if isinstance(p, dict) and p.get("type") == "text"]
        drex["state"] = text[0] if len(text) == 1 and isinstance(text[0], str) else state
        drex["images"] = _state_images(state)
    return drex, None


def _state_images(state):
    """The image URLs of OpenRouter `state` content parts, in order."""
    if not isinstance(state, list):
        return []
    return [
        p["image_url"].get("url")
        for p in state
        if isinstance(p, dict) and p.get("type") == "image_url" and isinstance(p.get("image_url"), dict)
    ]


def validate(body_bytes, body):
    """(served model, issues)."""
    issues = []
    if len(body_bytes) > MAX_BODY_BYTES:
        issues.append(_issue("", f"request body must be at most {MAX_BODY_BYTES} bytes"))
        return None, issues
    if not isinstance(body, dict):
        return None, [_issue("", "must be a JSON object")]
    if "state" not in body:
        issues.append(_issue("state", "is required"))
    questions = body.get("questions")
    if not isinstance(questions, dict):
        issues.append(_issue("questions", "must be an object"))
    elif not questions:
        issues.append(_issue("questions", "at least 1 question required"))
    elif len(questions) > MAX_QUESTIONS:
        issues.append(_issue("questions", f"at most {MAX_QUESTIONS} questions allowed"))
    else:
        for qid, raw in questions.items():
            if qid.strip() == "":
                issues.append(_issue("questions", "question ids must not be empty"))
                continue
            _parse_question(qid, raw, issues)
    model, model_issue = resolve_model(body.get("model"))
    if model_issue:
        issues.append(_issue("model", model_issue))
        return None, issues
    images = body.get("images")
    if images is not None:
        if not isinstance(images, list):
            issues.append(_issue("images", "must be an array"))
        else:
            if len(images) > MAX_IMAGES:
                issues.append(_issue("images", f"at most {MAX_IMAGES} images allowed"))
            if images and model not in IMAGE_MODELS:
                issues.append(_issue("images", f"images require {' or '.join(IMAGE_MODELS)}"))
            for i, image in enumerate(images):
                data = decode_image(image)
                if data is None:
                    issues.append(
                        _issue(
                            f"images.{i}",
                            "must be a PNG, JPEG or WebP base64 image, data URL, or workspace_file; URLs and paths "
                            "are not accepted",
                        )
                    )
                elif len(data) > MAX_IMAGE_BYTES:
                    issues.append(_issue(f"images.{i}", "image exceeds 16 MiB"))
    limits = QUESTION_LIMITS.get(model)
    if limits and isinstance(questions, dict):
        max_questions, max_options = limits
        label = SERVED[model]["label"]
        if len(questions) > max_questions:
            issues.append(_issue("questions", f"{label} allows at most {max_questions} questions."))
        for qid, q in questions.items():
            if (
                isinstance(q, dict)
                and q.get("type") in ("choice", "score")
                and isinstance(q.get("criteria"), (dict, list))
                and len(q["criteria"]) > max_options
            ):
                issues.append(
                    _issue(f"questions.{qid}.criteria", f"{label} allows at most {max_options} options or levels.")
                )
    return model, issues


def too_long(body, model):
    """Drex's 422 for a request over TOO_LONG_TOKENS, as upstreamFailed in lib/public-api.ts writes it, else None.

    A request with images is counted whole, as Drex Max counts it (issue path ""); one without, by its state."""
    state_tokens = len(json.dumps(body["state"]).encode()) // 4
    image_tokens = IMAGE_TOKENS * len(body.get("images") or [])
    limit = f"{TOO_LONG_TOKENS:,}"
    if image_tokens and state_tokens + image_tokens > TOO_LONG_TOKENS:
        message = (
            f"Request too long: the whole request (state, images, all questions and model formatting) exceeds the "
            f"{limit}-token limit of {model}. Shorten the state, use fewer or smaller images, or remove or shorten "
            f"questions."
        )
        return message, [_issue("", f"exceeds the {limit}-token whole-request limit")]
    if not image_tokens and state_tokens > TOO_LONG_TOKENS:
        message = f"Request too long: the state exceeds the {limit}-token state limit of {model}. Shorten the state."
        return message, [_issue("state", f"exceeds the {limit}-token state limit")]
    return None


